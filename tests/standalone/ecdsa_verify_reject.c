struct vec {
	const char* name;
	ccec_const_cp_t (*cp)(void);
	size_t nbytes; /* bytes in r, s and the order */
	const uint8_t* pub;
	size_t pub_len;
	const uint8_t* digest;
	size_t digest_len;
	const uint8_t* sig;
	size_t sig_len;
};

#define V(label, bits, pub, dig, sig) \
	{ label, ccec_cp_##bits, (bits + 7) / 8, pub, sizeof(pub), dig, sizeof(dig), sig, sizeof(sig) }

static const struct vec vecs[] = {
	V("P-256 RFC 6979 sha256/sample", 256, pub_256, d_256_sha256_sample, sig_256_sha256_sample),
	V("P-384 RFC 6979 sha384/sample", 384, pub_384, d_384_sha384_sample, sig_384_sha384_sample),
	V("P-192 openssl", 192, pub_192_openssl, dig_192_openssl, sig_192_openssl),
	V("P-256 openssl", 256, pub_256_openssl, dig_256_openssl, sig_256_openssl),
	V("P-384 openssl", 384, pub_384_openssl, dig_384_openssl, sig_384_openssl),
};

static int failures;

/* Run ccec_verify on exact-size heap copies so ASan sees any over-read. */
static bool verifies(const struct vec* v, const uint8_t* digest, const uint8_t* sig, size_t sig_len, int* rc_out) {
	ccec_const_cp_t cp = v->cp();
	ccec_pub_ctx_decl_cp(cp, key);
	if (ccec_import_pub(cp, v->pub_len, v->pub, key) != 0) {
		printf("FAIL %s: public key import\n", v->name);
		failures++;
		return false;
	}
	uint8_t* d = malloc(v->digest_len);
	uint8_t* s = malloc(sig_len ? sig_len : 1);
	memcpy(d, digest, v->digest_len);
	memcpy(s, sig, sig_len);
	bool valid = true; /* must be overwritten with false on rejection */
	int rc = ccec_verify(key, v->digest_len, d, sig_len, s, &valid);
	free(d);
	free(s);
	*rc_out = rc;
	return valid;
}

static void expect_reject(const struct vec* v, const char* what, const uint8_t* sig, size_t sig_len) {
	int rc;
	bool valid = verifies(v, v->digest, sig, sig_len, &rc);
	if (rc != 0 || valid) {
		printf("FAIL %s: %s: rc=%d valid=%d (want rc=0 valid=0)\n", v->name, what, rc, valid);
		failures++;
	}
}

/* Append an INTEGER holding the big-endian value x (leading zeros stripped). */
static size_t put_int(uint8_t* out, const uint8_t* x, size_t len) {
	while (len > 1 && x[0] == 0) {
		x++;
		len--;
	}
	size_t pad = (x[0] & 0x80) ? 1 : 0;
	out[0] = 0x02;
	out[1] = (uint8_t)(len + pad);
	if (pad)
		out[2] = 0;
	memcpy(out + 2 + pad, x, len);
	return 2 + pad + len;
}

/* SEQUENCE { INTEGER r, INTEGER s } with seq_len_adj added to the SEQUENCE length and
 * trailing zero bytes appended after the SEQUENCE; every length used here is below 128. */
static size_t build(uint8_t* out, const uint8_t* r, size_t rlen, const uint8_t* s, size_t slen, int seq_len_adj, size_t trailing) {
	size_t body = put_int(out + 2, r, rlen);
	body += put_int(out + 2 + body, s, slen);
	out[0] = 0x30;
	out[1] = (uint8_t)((int)body + seq_len_adj);
	memset(out + 2 + body, 0, trailing);
	return 2 + body + trailing;
}

static void run_vector(const struct vec* v) {
	const size_t nb = v->nbytes;
	int rc;

	/* positive control: the genuine signature verifies, with a flipped digest bit it does not */
	if (!verifies(v, v->digest, v->sig, v->sig_len, &rc) || rc != 0) {
		printf("FAIL %s: genuine signature rejected (rc=%d)\n", v->name, rc);
		failures++;
	}
	uint8_t bad_digest[64];
	memcpy(bad_digest, v->digest, v->digest_len);
	bad_digest[0] ^= 0x80;
	if (verifies(v, bad_digest, v->sig, v->sig_len, &rc)) {
		printf("FAIL %s: signature verifies for a different digest\n", v->name);
		failures++;
	}

	/* the group order, from the library's own curve parameters */
	ccec_const_cp_t cp = v->cp();
	uint8_t order[64], order_plus1[64], zero[64] = {0}, wide[65];
	ccn_write_uint_padded(ccec_cp_n(cp), ccec_cp_o(cp), nb, order);
	memcpy(order_plus1, order, nb);
	order_plus1[nb - 1] += 1; /* n is odd, so no carry */
	wide[0] = 1; /* 2^(8*nb) + 1 does not fit in nb bytes */
	memset(wide + 1, 0, nb);
	wide[nb] = 1;

	/* r and s of the genuine signature (all lengths are in short form) */
	const uint8_t* p = v->sig + 2;
	size_t rl = p[1];
	const uint8_t* rv = p + 2;
	p = rv + rl;
	size_t sl = p[1];
	const uint8_t* sv = p + 2;

	uint8_t buf[256];
	size_t len;
#define CASE_BUILD(what, r, rlen, s, slen, adj, trail) \
	len = build(buf, r, rlen, s, slen, adj, trail); \
	expect_reject(v, what, buf, len)

	CASE_BUILD("r = s = 0", zero, 1, zero, 1, 0, 0);
	CASE_BUILD("r = 0, s valid", zero, 1, sv, sl, 0, 0);
	CASE_BUILD("s = 0, r valid", rv, rl, zero, 1, 0, 0);
	CASE_BUILD("r = n", order, nb, sv, sl, 0, 0);
	CASE_BUILD("s = n", rv, rl, order, nb, 0, 0);
	CASE_BUILD("r = n + 1", order_plus1, nb, sv, sl, 0, 0);
	CASE_BUILD("s = n + 1", rv, rl, order_plus1, nb, 0, 0);
	CASE_BUILD("r wider than the field", wide, nb + 1, sv, sl, 0, 0);
	CASE_BUILD("s wider than the field", rv, rl, wide, nb + 1, 0, 0);
	CASE_BUILD("trailing byte after the SEQUENCE", rv, rl, sv, sl, 0, 1);
	CASE_BUILD("trailing byte inside the SEQUENCE", rv, rl, sv, sl, 1, 1);
	CASE_BUILD("SEQUENCE one byte shorter than its INTEGERs", rv, rl, sv, sl, -1, 0);
	CASE_BUILD("SEQUENCE one byte shorter, byte left over", rv, rl, sv, sl, -1, 1);

	/* A digest that truncates to e = 0 plus r = 0 makes u1 = u2 = 0, so R is the point at
	 * infinity, whose x is read back as 0 = r; only the range check stops that. */
	{
		uint8_t zero_digest[64] = {0};
		len = build(buf, zero, 1, sv, sl, 0, 0);
		bool valid = verifies(v, zero_digest, buf, len, &rc);
		if (rc != 0 || valid) {
			printf("FAIL %s: all-zero digest with r = 0: rc=%d valid=%d\n", v->name, rc, valid);
			failures++;
		}
	}

	/* a genuine signature, damaged */
	memcpy(buf, v->sig, v->sig_len);
	expect_reject(v, "truncated by one byte", buf, v->sig_len - 1);
	memcpy(buf, v->sig, v->sig_len);
	buf[0] = 0x31;
	expect_reject(v, "SET instead of SEQUENCE", buf, v->sig_len);
	memcpy(buf, v->sig, v->sig_len);
	buf[2] = 0x04;
	expect_reject(v, "OCTET STRING instead of INTEGER", buf, v->sig_len);

	/* structural minimums */
	expect_reject(v, "empty signature", buf, 0);
	static const uint8_t empty_seq[] = {0x30, 0x00};
	expect_reject(v, "30 00", empty_seq, sizeof empty_seq);
	static const uint8_t zero_zero[] = {0x30, 0x06, 0x02, 0x01, 0x00, 0x02, 0x01, 0x00};
	expect_reject(v, "30 06 02 01 00 02 01 00", zero_zero, sizeof zero_zero);
	static const uint8_t only_r[] = {0x30, 0x03, 0x02, 0x01, 0x05};
	expect_reject(v, "SEQUENCE with a single INTEGER", only_r, sizeof only_r);
	static const uint8_t wrong_tag[] = {0x31, 0x06, 0x02, 0x01, 0x05, 0x02, 0x01, 0x07};
	expect_reject(v, "wrong tag, small r and s", wrong_tag, sizeof wrong_tag);
}

int main(void) {
	for (size_t i = 0; i < sizeof(vecs) / sizeof(vecs[0]); i++)
		run_vector(&vecs[i]);
	printf("%d failure(s)\n", failures);
	return failures != 0;
}
