struct vec {
	const char* name;
	const uint8_t* digest;
	size_t digest_len;
	const uint8_t* sig;
	size_t sig_len;
};

#define V(id, label) {label, d_521_##id, sizeof d_521_##id, sig_521_##id, sizeof sig_521_##id},
static const struct vec cases[] = {P521_VECTORS};
#undef V

static int import(size_t len, const uint8_t* in) {
	ccec_const_cp_t cp = ccec_cp_521();
	ccec_pub_ctx_decl_cp(cp, key);
	uint8_t* buf = malloc(len ? len : 1);
	memcpy(buf, in, len);
	int rc = ccec_import_pub(cp, len, buf, key);
	free(buf);
	return rc;
}

static bool verifies(size_t i, bool corrupt) {
	ccec_const_cp_t cp = ccec_cp_521();
	ccec_pub_ctx_decl_cp(cp, key);
	uint8_t* pub = malloc(sizeof pub_521);
	memcpy(pub, pub_521, sizeof pub_521);
	int rc = ccec_import_pub(cp, sizeof pub_521, pub, key);
	free(pub);
	if (rc != 0)
		return false;

	uint8_t* digest = malloc(cases[i].digest_len);
	uint8_t* sig = malloc(cases[i].sig_len);
	memcpy(digest, cases[i].digest, cases[i].digest_len);
	memcpy(sig, cases[i].sig, cases[i].sig_len);
	if (corrupt)
		sig[cases[i].sig_len - 1] ^= 0x01;

	bool valid = false;
	rc = ccec_verify(key, cases[i].digest_len, digest, cases[i].sig_len, sig, &valid);
	free(digest);
	free(sig);
	return rc == 0 && valid;
}

