# Writes src/ccdh_modp_groups.h, the primes of the MODP Diffie-Hellman groups
# of RFC 2409 section 6.2 (group 2) and RFC 3526 (groups 5 and 14 to 18).
# Both RFCs define each prime as
#     p = 2^n - 2^(n-64) - 1 + 2^64 * (floor(2^(n-130) * pi) + k)
# and give k; the primes are computed from that formula here (pi by Machin's
# formula in integer arithmetic). The RFCs also print the primes in
# hexadecimal: pass the RFC text files with --check to compare.
#
# usage: scripts/generate-modp-groups.py > src/ccdh_modp_groups.h
#        scripts/generate-modp-groups.py --check rfc2409.txt rfc3526.txt

import re
import sys

GROUPS = [
    # name, bits, k
    ('rfc2409group02', 1024, 129093),
    ('rfc3526group05', 1536, 741804),
    ('rfc3526group14', 2048, 124476),
    ('rfc3526group15', 3072, 1690314),
    ('rfc3526group16', 4096, 240904),
    ('rfc3526group17', 6144, 929484),
    ('rfc3526group18', 8192, 4743158),
]


def pi_times_power_of_two(bits):
    """floor(pi * 2^bits)"""
    guard = 64
    one = 1 << (bits + guard)

    def arctan_of_inverse(x):
        term = one // x
        total = term
        x2 = x * x
        k = 1
        while term:
            term //= x2
            part = term // (2 * k + 1)
            total += -part if k % 2 else part
            k += 1
        return total

    return (16 * arctan_of_inverse(5) - 4 * arctan_of_inverse(239)) >> guard


def modp_prime(bits, k):
    return 2**bits - 2**(bits - 64) - 1 + 2**64 * (pi_times_power_of_two(bits - 130) + k)


def rfc_primes(path):
    """{bits: prime} for every hexadecimal prime printed in an RFC text"""
    lines = [l for l in open(path).read().split('\n')
             if '[Page ' not in l and not l.startswith('RFC ') and '\f' not in l]
    text = '\n'.join(lines)
    found = {}
    pattern = (r'prime is:?\s*2\^(\d+)[^\n]*\n(?:[^\n]*\n){0,2}?\s*Its hexadecimal value is:?\s*\n'
               r'((?:\s*[0-9A-F]{8}(?: [0-9A-F]{8})*\s*\n)+)')
    for m in re.finditer(pattern, text):
        found[int(m.group(1))] = int(re.sub(r'\s', '', m.group(2)), 16)
    return found


def check(paths):
    printed = {}
    for path in paths:
        printed.update(rfc_primes(path))
    ok = True
    for name, bits, k in GROUPS:
        same = printed.get(bits) == modp_prime(bits, k)
        ok &= same
        print('%s (%d bits): %s' % (name, bits, 'matches the RFC' if same else 'MISMATCH'))
    return 0 if ok else 1


def generate():
    out = sys.stdout
    out.write('/* Generated by scripts/generate-modp-groups.py; do not edit. */\n\n')
    for name, bits, k in GROUPS:
        p = modp_prime(bits, k)
        assert p.bit_length() == bits
        data = p.to_bytes(bits // 8, 'big')
        out.write('/* %d-bit MODP prime: 2^%d - 2^%d - 1 + 2^64 * (floor(2^%d pi) + %d) */\n'
                  % (bits, bits, bits - 64, bits - 130, k))
        out.write('static const uint8_t modp_%s_prime[%d] = {\n' % (name, len(data)))
        for i in range(0, len(data), 12):
            out.write('\t' + ', '.join('0x%02x' % b for b in data[i:i + 12]) + ',\n')
        out.write('};\n\n')
    return 0


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == '--check':
        sys.exit(check(sys.argv[2:]))
    sys.exit(generate())
